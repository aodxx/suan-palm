// ระยะปลูก (ด้านของสามเหลี่ยมด้านเท่า) หน่วยเมตร
const SPACING = 9;

/* ---------------------------------------------------------------------
 * 1) ระยะห่างระหว่างแถว (Row Spacing)
 *    สามเหลี่ยมด้านเท่า ด้านยาว s : มุมทุกมุม = 60°
 *    ต้นในแถวถัดไปอยู่กึ่งกลางระหว่าง 2 ต้นของแถวก่อนหน้า (เยื้อง s/2)
 *    ความสูงของสามเหลี่ยม = ระยะห่างแถว
 *        h = s × sin(60°) = s × (√3 / 2)
 *    s = 9  →  h = 9 × 0.8660254 = 7.794 เมตร
 * --------------------------------------------------------------------- */
const ROW_SPACING = SPACING * Math.sin(Math.PI / 3);   // = 9 * (√3/2) ≈ 7.794 ม.

/* ---------------------------------------------------------------------
 * 2) พื้นที่ที่แต่ละต้นใช้ และจำนวนต้นต่อไร่
 *    พื้นที่ต่อ 1 ต้น = ระยะระหว่างต้น × ระยะระหว่างแถว = s × h = s² × (√3/2)
 *                      = 9 × 7.794 = 70.15 ตร.ม./ต้น
 *    (เทียบกับปลูกแบบสี่เหลี่ยมจัตุรัส 9×9 = 81 ตร.ม./ต้น → แน่นกว่า ~15.5%)
 *    1 ไร่ = 1,600 ตร.ม.
 *    ต้นต่อไร่ = 1600 / 70.15 = 22.81 ≈ 22 ต้น (ปัดลงเพราะต้นเป็นเศษไม่ได้)
 * --------------------------------------------------------------------- */
const AREA_PER_TREE = SPACING * ROW_SPACING;            // ≈ 70.148 ตร.ม.
const RAI_M2 = 1600;
const TREES_PER_RAI = RAI_M2 / AREA_PER_TREE;           // ≈ 22.81

/* ---------------------------------------------------------------------
 * 3) แปลงพื้นที่ (ตร.ม.) → ไร่ งาน ตารางวา
 *    1 ตารางวา = 4 ตร.ม.
 *    1 งาน     = 100 ตารางวา = 400 ตร.ม.
 *    1 ไร่     = 4 งาน = 400 ตารางวา = 1,600 ตร.ม.
 *    ขั้นตอน: ตร.ม. ÷ 4 = ตารางวารวม → ไร่ = floor(วา/400)
 *            เศษ → งาน = floor(เศษ/100) → เศษที่เหลือ = ตารางวา
 *    (คำนวณเป็นหน่วย "ร้อยละของตารางวา" แบบจำนวนเต็ม เพื่อกัน 100.00 ปัดเกิน)
 * --------------------------------------------------------------------- */
function m2ToThaiArea(m2) {
  const units = Math.round((m2 / 4) * 100);   // ตารางวา × 100
  const rai   = Math.floor(units / 40000);    // 400 วา = 40000 หน่วย
  const rem   = units % 40000;
  const ngan  = Math.floor(rem / 10000);      // 100 วา = 10000 หน่วย
  const wa    = (rem % 10000) / 100;
  return { rai, ngan, wa };
}
